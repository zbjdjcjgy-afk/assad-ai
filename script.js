const langSelect = document.getElementById("language");
function setLanguage(lang){
  const t=translations[lang]||translations.en;
  document.documentElement.lang=lang;
  document.documentElement.dir=lang==="ar"?"rtl":"ltr";
  document.querySelectorAll("[data-i18n]").forEach(el=>{
    const key=el.dataset.i18n;if(t[key]!==undefined)el.innerHTML=t[key];
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el=>{
    const key=el.dataset.i18nPlaceholder;if(t[key]!==undefined)el.placeholder=t[key];
  });
  langSelect.value=lang;
  document.querySelectorAll(".suggestion").forEach((btn,i)=>{
    const labels={en:["Online store","Learn coding","Grow an audience"],ar:["متجر إلكتروني","تعلم البرمجة","زيادة الجمهور"],fr:["Boutique en ligne","Apprendre à coder","Développer son audience"]};
    btn.textContent=labels[lang][i];
  });
}
langSelect.addEventListener("change",e=>setLanguage(e.target.value));
const goal=document.getElementById("goal"),count=document.getElementById("char-count");
goal.addEventListener("input",()=>count.textContent=`${goal.value.length} / 500`);
document.querySelectorAll(".suggestion").forEach(btn=>btn.addEventListener("click",()=>{
  goal.value=btn.dataset.example;count.textContent=`${goal.value.length} / 500`;goal.focus();
}));
let currentPlan=[];
document.getElementById("goal-form").addEventListener("submit",e=>{
  e.preventDefault();
  const value=goal.value.trim();if(!value)return;
  const lang=langSelect.value,t=translations[lang]||translations.en;
  currentPlan=t.steps;
  document.getElementById("result-title").textContent=value;
  const list=document.getElementById("plan-list");list.replaceChildren();
  currentPlan.forEach(step=>{const li=document.createElement("li");li.textContent=step;list.appendChild(li);});
  document.getElementById("result").classList.remove("hidden");
  document.getElementById("result").scrollIntoView({behavior:"smooth",block:"nearest"});
});
document.getElementById("copy-plan").addEventListener("click",async()=>{
  const title=document.getElementById("result-title").textContent;
  const text=[title,"",...currentPlan.map((s,i)=>`${i+1}. ${s}`)].join("\n");
  const btn=document.getElementById("copy-plan");
  try{await navigator.clipboard.writeText(text);btn.textContent=langSelect.value==="ar"?"تم النسخ!":langSelect.value==="fr"?"Copié !":"Copied!";}
  catch{btn.textContent=langSelect.value==="ar"?"تعذر النسخ":"Copy unavailable";}
});
